"""Deterministic vendor adapter evals (Option A, PR #66 WP2).

No LLM, no network, stdlib only. Vendored skills live under
vendor/addy-agent-skills/skills/ and are exempt from the native
structure gate (docs/skill-format.md): their headings do not match
the native literal titles — only 1 of 26 has a literal `## Process`
and using-agent-skills has no standard sections at all — and
retitling them would break byte identity with upstream (red line
R1). So this runner checks what can be checked portably, in three
families:

1. Frontmatter: every vendored SKILL.md must carry frontmatter with
   a well-formed name equal to its directory name and a non-empty
   description. A missing "Use when" trigger clause is a soft
   recommendation only (same convention as the native evals).
   No section-concept checks are applied to vendored files.

2. Routing: every case in evals/vendor-routing-cases.json (one per
   vendored skill, 26 total) must resolve to a skill that exists
   under vendor/addy-agent-skills/skills/ and is named by
   skills/chef-orchestrator/SKILL.md (whole-file word-boundary
   match, same parse basis as the native evals). The interview-me
   case proves the name is routed; the routing target is the native
   interview-me — the vendored copy is reference-only.

3. Index coverage: docs/skill-index.json (generated by
   tools/generate_skill_index.py) must list all 26 vendored + 6
   native skills, with the right source, the right installable
   verdict (only vendored interview-me is reference-only), and a
   sha256 per SKILL.md that matches the working tree — so an
   accidental edit to a vendored SKILL.md is caught here.

What this runner does NOT check: full-tree byte identity against
upstream. That needs the upstream clone and is WP1 evidence (cmp
records in ~/workspace/aka-skills-review/), not a deterministic
eval — the evals run in CI with no network and no clone.

Exit code: 0 when every hard check passes, 1 otherwise. Soft
recommendations never change the exit code.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

from evals.run_evals import (
    NAME_RE,
    check_routing,
    discover_skills,
    load_routing_cases,
    parse_frontmatter,
)

VENDOR_SKILLS_DIR = Path("vendor") / "addy-agent-skills" / "skills"
REFERENCE_ONLY_VENDOR = {"interview-me"}


def check_vendor_frontmatter(skill_dir):
    """Frontmatter-only check for one vendored skill dir.

    Hard-fails on: missing frontmatter, bad or missing name, name !=
    directory name, empty description. A description without
    "Use when" is a soft recommendation only.
    """
    skill_dir = Path(skill_dir)
    path = skill_dir / "SKILL.md"
    result = {
        "skill": skill_dir.name,
        "path": str(path),
        "ok": False,
        "problems": [],
        "frontmatter": {"present": False},
        "recommendations": [],
    }
    if not path.is_file():
        result["problems"].append("SKILL.md missing")
        return result
    text = path.read_text(encoding="utf-8")
    frontmatter = parse_frontmatter(text)
    name = (frontmatter or {}).get("name", "")
    description = (frontmatter or {}).get("description", "")
    name_ok = bool(NAME_RE.match(name or ""))
    name_matches_dir = name == skill_dir.name
    description_ok = bool(description and description.strip())
    has_use_when = "use when" in description.lower()
    result["frontmatter"] = {
        "present": frontmatter is not None,
        "name_ok": name_ok,
        "name_matches_dir": name_matches_dir,
        "description_ok": description_ok,
        "description_has_use_when": has_use_when,
    }
    if frontmatter is None:
        result["problems"].append("frontmatter missing")
    if not name_ok:
        result["problems"].append(f"bad frontmatter name: {name!r}")
    if name_ok and not name_matches_dir:
        result["problems"].append(
            f"frontmatter name {name!r} != directory {skill_dir.name!r}"
        )
    if not description_ok:
        result["problems"].append("empty description")
    if description_ok and not has_use_when:
        result["recommendations"].append(
            "description lacks 'Use when' trigger language"
        )
    result["ok"] = not result["problems"]
    return result


def check_index_coverage(repo_root, index_path=None):
    """The generated index must cover all 32 skills, with the right
    source, installable verdict, and SKILL.md sha256 per entry."""
    repo_root = Path(repo_root)
    index_path = (
        Path(index_path) if index_path else repo_root / "docs" / "skill-index.json"
    )
    result = {
        "index": str(index_path),
        "ok": False,
        "problems": [],
        "counts": {},
    }
    if not index_path.is_file():
        result["problems"].append(f"index missing: {index_path}")
        return result
    try:
        index = json.loads(index_path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        result["problems"].append(f"index is not valid JSON: {exc}")
        return result
    entries = {}
    for e in index.get("skills", []):
        # Keyed by (source, name): native and vendored interview-me
        # share a name and must not collapse into one entry.
        entries[(e.get("source"), e.get("name"))] = e
    native_dirs = discover_skills(repo_root / "skills")
    vendor_dirs = discover_skills(repo_root / VENDOR_SKILLS_DIR)
    result["counts"] = {
        "native": len(native_dirs),
        "vendor": len(vendor_dirs),
        "index_entries": len(index.get("skills", [])),
    }
    for skill_dir in native_dirs:
        entry = entries.get(("native", skill_dir.name))
        if entry is None:
            result["problems"].append(f"index missing native skill: {skill_dir.name}")
            continue
        if entry.get("source") != "native":
            result["problems"].append(
                f"index source wrong for {skill_dir.name}: {entry.get('source')!r}"
            )
        if entry.get("installable") is not True:
            result["problems"].append(
                f"index marks native {skill_dir.name} not installable"
            )
        _check_entry_hash(skill_dir, entry, result)
    for skill_dir in vendor_dirs:
        entry = entries.get(("vendor", skill_dir.name))
        if entry is None:
            result["problems"].append(f"index missing vendored skill: {skill_dir.name}")
            continue
        if entry.get("source") != "vendor":
            result["problems"].append(
                f"index source wrong for {skill_dir.name}: {entry.get('source')!r}"
            )
        want_installable = skill_dir.name not in REFERENCE_ONLY_VENDOR
        if entry.get("installable") is not want_installable:
            result["problems"].append(
                f"index installable wrong for {skill_dir.name}: "
                f"{entry.get('installable')!r}, want {want_installable}"
            )
        _check_entry_hash(skill_dir, entry, result)
    known = {("native", p.name) for p in native_dirs} | {
        ("vendor", p.name) for p in vendor_dirs
    }
    for source, name in sorted(entries):
        if (source, name) not in known:
            result["problems"].append(f"index lists unknown skill: {source}/{name}")
    result["ok"] = not result["problems"]
    return result


def _check_entry_hash(skill_dir, entry, result):
    """Compare a recorded sha256 against the SKILL.md on disk.

    The hash must be computed over the same LF-normalised content the
    generator records (tools/generate_skill_index.py reads the file in
    text mode, which folds CRLF to LF). Hashing raw disk bytes would
    mismatch every skill on a Windows checkout, where git converts LF
    to CRLF — CI test (windows-latest) failed on all 32 skills for
    exactly this reason. Do not "fix" this by forcing line endings;
    the anchor itself must be line-ending insensitive.
    """
    recorded = entry.get("sha256", "")
    path = skill_dir / "SKILL.md"
    if not recorded:
        result["problems"].append(f"index entry {skill_dir.name} has no sha256")
        return
    actual = hashlib.sha256(path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    if recorded != actual:
        result["problems"].append(
            f"sha256 mismatch for {skill_dir.name}: index {recorded[:12]}… "
            f"!= disk {actual[:12]}… (regenerate the index or restore the file)"
        )


def run_vendor_all(repo_root, cases_path=None, orchestrator_path=None,
                   index_path=None):
    """Run all three vendor check families; return a report dict."""
    repo_root = Path(repo_root)
    vendor_dir = repo_root / VENDOR_SKILLS_DIR
    cases_path = (
        Path(cases_path)
        if cases_path
        else repo_root / "evals" / "vendor-routing-cases.json"
    )
    orchestrator_path = (
        Path(orchestrator_path)
        if orchestrator_path
        else repo_root / "skills" / "chef-orchestrator" / "SKILL.md"
    )
    frontmatter = [
        check_vendor_frontmatter(p) for p in discover_skills(vendor_dir)
    ]
    cases = load_routing_cases(cases_path)
    routing = check_routing(vendor_dir, orchestrator_path, cases)
    index = check_index_coverage(repo_root, index_path)
    summary = {
        "frontmatter_checked": len(frontmatter),
        "frontmatter_ok": sum(1 for s in frontmatter if s["ok"]),
        "routing_cases": len(routing),
        "routing_ok": sum(1 for r in routing if r["ok"]),
        "index_ok": bool(index["ok"]),
        "recommendations": sum(
            len(s.get("recommendations", [])) for s in frontmatter
        ),
    }
    return {
        "frontmatter": frontmatter,
        "routing": routing,
        "index": index,
        "summary": summary,
    }


def format_summary(report):
    """One line per failure plus counts."""
    lines = []
    for skill in report["frontmatter"]:
        if skill["ok"]:
            lines.append(f"  OK   {skill['skill']}")
        else:
            lines.append(
                f"  FAIL {skill['skill']}: {'; '.join(skill['problems'])}"
            )
    for case in report["routing"]:
        if not case["ok"]:
            lines.append(
                f"  FAIL {case['id']} -> {case['expected_skill']}: {case['reason']}"
            )
    if not report["index"]["ok"]:
        for problem in report["index"]["problems"]:
            lines.append(f"  FAIL index: {problem}")
    summary = report["summary"]
    lines.append(
        f"frontmatter {summary['frontmatter_ok']}/{summary['frontmatter_checked']} ok; "
        f"routing {summary['routing_ok']}/{summary['routing_cases']} ok; "
        f"index {'ok' if summary['index_ok'] else 'FAIL'}; "
        f"{summary['recommendations']} soft recommendation(s)"
    )
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Deterministic vendor adapter evals (no LLM, no network)."
    )
    parser.add_argument(
        "--root",
        default=str(Path(__file__).resolve().parents[1]),
        help="Repo root (default: parent of evals/).",
    )
    parser.add_argument("--cases", default=None, help="Vendor routing cases JSON path.")
    parser.add_argument(
        "--orchestrator", default=None, help="chef-orchestrator SKILL.md path."
    )
    parser.add_argument("--index", default=None, help="Generated skill index JSON path.")
    parser.add_argument("--json", action="store_true", help="Print the full report as JSON.")
    args = parser.parse_args(argv)
    report = run_vendor_all(args.root, args.cases, args.orchestrator, args.index)
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print(format_summary(report))
    hard_ok = (
        report["summary"]["frontmatter_ok"]
        == report["summary"]["frontmatter_checked"]
        and report["summary"]["routing_ok"] == report["summary"]["routing_cases"]
        and report["summary"]["index_ok"]
    )
    return 0 if hard_ok else 1


if __name__ == "__main__":
    sys.exit(main())
